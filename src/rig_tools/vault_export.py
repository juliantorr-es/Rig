GENERATED_HEADER = "<!-- GENERATED BY RIG VAULT EXPORT. DO NOT EDIT THIS GENERATED NOTE DIRECTLY. SOURCE OF TRUTH IS RIG RECEIPTS/STATE. -->"


@dataclass
class VaultNote:
    """Represents a single vault note with frontmatter and body."""
    note_id: str
    rig_type: str
    title: str
    path: str
    frontmatter: Dict[str, Any]
    body_sections: List[str]
    links: List[str] = field(default_factory=list)
    source_artifacts: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    status: str = "pass"

    def to_markdown(self) -> str:
        """Render note as Markdown with YAML frontmatter."""
        lines = [GENERATED_HEADER, ""]
        lines.append("---")
        for key, value in self.frontmatter.items():
            if isinstance(value, list):
                if value:
                    lines.append(f"{key}:")
                    for item in value:
                        lines.append(f"  - {item}")
            elif isinstance(value, bool):
                lines.append(f"{key}: {str(value).lower()}")
            elif value is not None:
                lines.append(f"{key}: {value}")
            else:
                lines.append(f"{key}:")
        lines.append("---")
        lines.append("")
        lines.extend(self.body_sections)
        return "\n".join(lines)


@dataclass
class ExportManifest:
    """Represents a vault export manifest."""
    schema_version: str = "rig.vault_export.v1"
    export_id: str = ""
    created_at: str = ""
    status: str = "pass"
    vault_path: str = ""
    note_count: int = 0
    task_note_count: int = 0
    copied_json_count: int = 0
    copied_bundle_count: int = 0
    source_artifacts: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    notes: List[Dict[str, Any]] = field(default_factory=list)
    authoritative: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "export_id": self.export_id,
            "created_at": self.created_at,
            "status": self.status,
            "vault_path": self.vault_path,
            "note_count": self.note_count,
            "task_note_count": self.task_note_count,
            "copied_json_count": self.copied_json_count,
            "copied_bundle_count": self.copied_bundle_count,
            "source_artifacts": self.source_artifacts,
            "warnings": self.warnings,
            "notes": self.notes,
            "authoritative": self.authoritative,
        }


