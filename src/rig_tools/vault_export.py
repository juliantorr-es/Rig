    def collect_all_notes(self, copy_json: bool = False, copy_bundles: bool = False) -> List[VaultNote]:
        """Collects all notes to be exported."""
        notes: List[VaultNote] = []

        # Always include required notes
        notes.append(self.build_dashboard_note())
        notes.append(self.build_tasks_index_note())
        notes.append(self.build_runs_index_note())
        notes.append(self.build_loops_index_note())
        notes.append(self.build_sentinels_index_note())
        notes.append(self.build_scheduler_index_note())
        notes.append(self.build_gc_index_note())
        notes.append(self.build_anigma_index_note())
        notes.append(self.build_anigma_sentinel_note())
        notes.append(self.build_settings_reference_note())
        notes.append(self.build_actions_reference_note())

        # Add sentinel note if receipt exists
        sentinel_note = self.build_sentinel_note()
        if sentinel_note:
            notes.append(sentinel_note)

        # Add task notes
        try:
            with self.state_store.connect() as conn:
                res = conn.execute("SELECT * FROM tasks").fetchall()
                tasks = [dict(r) for r in res]
        except Exception:
            tasks = []

        for task in tasks:
            notes.append(self.build_task_note(task))

        # Add loop run notes
        try:
            with self.state_store.connect() as conn:
                res = conn.execute("SELECT * FROM loop_runs").fetchall()
                loop_runs = [dict(r) for r in res]
        except Exception:
            loop_runs = []

        for loop_run in loop_runs:
            notes.append(self.build_loop_note(loop_run))

        # Track source artifacts
        self.source_artifacts = list(set(self.source_artifacts + [
            ".build/rig/state/rig.sqlite",
            ".build/rig/os-sentinel/latest.json",
        ]))

        # Copy JSON receipts if requested
        if copy_json:
            self._copy_json_receipts()

        # Copy bundles if requested
        if copy_bundles:
            self._copy_bundles()

        return notes

    def _copy_json_receipts(self):
        """Copies selected JSON receipts to vault attachments."""
        attachments_json_dir = self.vault_root / "Attachments" / "json"
        attachments_json_dir.mkdir(parents=True, exist_ok=True)

        # Copy key receipts
        receipt_paths = [
            ".build/rig/os-sentinel/latest.json",
            ".build/rig/state/status.json" if (self.repo_root / ".build" / "rig" / "state" / "status.json").exists() else None,
            ".build/rig/projections/latest.json" if (self.repo_root / ".build" / "rig" / "projections" / "latest.json").exists() else None,
        ]

        for path_str in receipt_paths:
            if path_str:
                src = self.repo_root / path_str
                if src.exists():
                    dst = attachments_json_dir / src.name
                    dst.write_text(src.read_text(encoding="utf-8"), encoding="utf-8")
                    self.copied_json_count += 1
                    self.source_artifacts.append(path_str)

    def _copy_bundles(self):
        """Copies selected bundle manifests to vault attachments."""
        attachments_bundles_dir = self.vault_root / "Attachments" / "bundles"
        attachments_bundles_dir.mkdir(parents=True, exist_ok=True)

        # Copy session bundle manifests if they exist
        session_bundles_dir = self.repo_root / "Session-bundles"
        if session_bundles_dir.exists():
            for manifest in session_bundles_dir.glob("*.manifest.json"):
                dst = attachments_bundles_dir / manifest.name
                dst.write_text(manifest.read_text(encoding="utf-8"), encoding="utf-8")
                self.copied_bundle_count += 1
                self.source_artifacts.append(str(manifest.relative_to(self.repo_root)))

    def export(self, dry_run: bool = False, copy_json: bool = False, copy_bundles: bool = False) -> ExportManifest:
        """Exports all notes to the vault."""
        notes = self.collect_all_notes(copy_json=copy_json, copy_bundles=copy_bundles)

        manifest = ExportManifest(
            schema_version="rig.vault_export.v1",
            export_id=self.export_id,
            created_at=self.created_at,
            status="pass",
            vault_path=str(self.vault_root.relative_to(self.repo_root)),
            note_count=len(notes),
            task_note_count=sum(1 for n in notes if n.rig_type == "task"),
            copied_json_count=self.copied_json_count,
            copied_bundle_count=self.copied_bundle_count,
            source_artifacts=self.source_artifacts,
            warnings=self.warnings,
            authoritative=False,
        )

        if dry_run:
            # Write dry-run preview receipt only
            dry_run_dir = self.repo_root / ".build" / "rig" / "vault" / "dry-run"
            dry_run_dir.mkdir(parents=True, exist_ok=True)
            
            # Write manifest
            manifest_path = dry_run_dir / f"{self.export_id}.json"
            manifest_path.write_text(json.dumps(manifest.to_dict(), indent=2), encoding="utf-8")

            # Write preview of each note (truncated)
            preview_dir = dry_run_dir / "preview"
            preview_dir.mkdir(exist_ok=True)
            for note in notes:
                preview_path = preview_dir / f"{note.note_id}.preview.md"
                content = note.to_markdown()
                if len(content) > 2000:
                    content = content[:2000] + "\n\n... (truncated)"
                preview_path.write_text(content, encoding="utf-8")

            manifest.status = "dry_run"
            manifest.vault_path = str(preview_dir.relative_to(self.repo_root))
            return manifest

        # Write actual vault notes
        self.vault_root.mkdir(parents=True, exist_ok=True)

        written_count = 0
        for note in notes:
            note_path = self.vault_root / note.path
            note_path.parent.mkdir(parents=True, exist_ok=True)
            note_path.write_text(note.to_markdown(), encoding="utf-8")
            written_count += 1

            # Add to manifest notes
            manifest.notes.append({
                "note_id": note.note_id,
                "rig_type": note.rig_type,
                "title": note.title,
                "path": note.path,
                "source_artifacts": note.source_artifacts,
                "links": note.links,
                "frontmatter": note.frontmatter,
                "status": note.status,
                "warnings": note.warnings,
            })

        # Write manifest
        manifest_path = self.vault_root / "rig-vault-export-manifest.json"
        manifest_path.write_text(json.dumps(manifest.to_dict(), indent=2), encoding="utf-8")

        # Update status based on warnings
        if manifest.warnings:
            manifest.status = "warn"

        return manifest

    def get_obsidian_uri(self, note_path: str, vault_name: str = "Rig-vault") -> str:
        """Generates an Obsidian URI for a note."""
        # Percent-encode the file path including forward slashes
        encoded_path = urllib.parse.quote(note_path, safe='')
        return f"obsidian://open?vault={vault_name}&file={encoded_path}"
