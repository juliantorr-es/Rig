"""Rig OS Vault Export - Obsidian-compatible Markdown vault projection.

Doctrine:
- Vault is a projection, not source of truth.
- Markdown is for human-operable memory.
- JSON/JSONL receipts remain machine evidence.
- SQLite is operational state.
- Projections are rebuildable read models.
- Vault export must be deterministic.
- Vault export must default to dry-run unless explicitly writing.
- Vault export must not mutate source docs.
- Vault export must not move/archive/delete files.
"""

