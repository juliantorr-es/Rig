    def build_scheduler_index_note(self) -> VaultNote:
        """Builds the 08 Scheduler/index.md note."""
        scheduler_jobs = []
        try:
            with self.state_store.connect() as conn:
                res = conn.execute("SELECT * FROM scheduler_jobs").fetchall()
                scheduler_jobs = [dict(r) for r in res]
        except Exception as e:
            self.warnings.append(f"Could not read scheduler_jobs from state store: {e}")

        body = [
            "# Scheduler",
            "",
            "Rig OS background job scheduling status.",
            "",
            "## Known Jobs",
            f"",
            f"- **Total Jobs**: {len(scheduler_jobs)}",
            "",
        ]

        if scheduler_jobs:
            body.append("## Job Status")
            body.append("")
            for job in scheduler_jobs:
                name = job.get("job_name", "")
                schedule = job.get("schedule", "")
                enabled = job.get("data", {})
                # Parse data for enabled status
                data = job.get("data") or {}
                try:
                    job_data = json.loads(data) if isinstance(data, str) else data
                    enabled = job_data.get("enabled", True)
                except Exception:
                    enabled = True
                status_str = "Enabled" if enabled else "Disabled"
