"""Base Runtime Adapter for Rig.

This module provides the base class for all runtime adapters.

Core doctrine:
- Models propose; Rig governs.
- Adapters NEVER directly mutate authority state.
- All adapter outputs are proposals that must be validated.
- Adapters are replay-safe and deterministic where possible.

file: src/rig/domain/runtimes/base.py
"""

